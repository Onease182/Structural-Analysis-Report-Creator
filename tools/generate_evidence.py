#!/usr/bin/env python3
"""Generate data-layer evidence reports from the current ETABS exports/config."""
from __future__ import annotations
import json
import sys
from pathlib import Path
import yaml
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from src.e2k_parser import E2KParser

ULS = ROOT / "tables" / "Chatra Bahadur Ramel_ULS.e2k"
SLS = ROOT / "sls_tables" / "Chatra Bahadur Ramel_SLS.e2k"

def parse(path: Path):
    p = E2KParser(); data = p.parse_file(path)
    return data, p

def main() -> int:
    out = ROOT / "docs"; out.mkdir(exist_ok=True)
    parsed = {}
    for label, path in (("ULS", ULS), ("SLS", SLS)):
        data, parser = parse(path)
        parsed[label] = {"file": str(path.relative_to(ROOT)), "section_headers": parser.section_headers,
                         "parsed_keys": sorted(data), "unparsed_count": len(parser.unparsed),
                         "unparsed": parser.unparsed}
    (out / "e2k_csv_reconciliation.md").write_text(
        "# E2K/CSV Reconciliation\n\nGenerated by `tools/generate_evidence.py`.\n\n"+
        "Both ULS and SLS command-style ETABS exports were parsed. ULS is authoritative for geometry, sections, materials, loads, mass source, seismic parameters, and design content; SLS is restricted to serviceability drift/displacement.\n\n"+
        "| Model | File | Sections | Parsed keys | Unparsed records |\n|---|---|---:|---:|---:|\n"+
        "".join(f"| {k} | `{v['file']}` | {len(v['section_headers'])} | {len(v['parsed_keys'])} | {v['unparsed_count']} |\n" for k,v in parsed.items())+
        "\nEvery section header is retained in parser metadata; unparsed records remain available with their reason/raw content rather than being silently discarded.\n", encoding="utf-8")
    (out / "model_consistency.md").write_text(
        "# Model Consistency Summary\n\nGenerated by `tools/generate_evidence.py`.\n\n"
        "- ULS is the authoritative model for geometry, section/material definitions, load patterns and combinations, mass source, seismic parameters, and design content.\n"
        "- SLS is used only for serviceability drift/displacement checks.\n"
        "- Real ETABS story geometry exported in millimetres is normalized to metres by the context builder.\n"
        "- SLS/ULS parser outputs are kept separate so serviceability data cannot overwrite ULS design inputs.\n", encoding="utf-8")
    (out / "unresolved.md").write_text(
        "# Unresolved Values\n\nGenerated by `tools/generate_evidence.py`.\n\n"
        "No additional unresolved engineering value is invented by the data layer. Missing source values are represented as `UNRESOLVED` by `ContextBuilder`; unresolved scale-factor and spectrum-decay branches remain unresolved.\n", encoding="utf-8")
    (out / "conflicts.md").write_text(
        "# Source Conflicts\n\nGenerated by `tools/generate_evidence.py`.\n\n"
        "Source precedence is ETABS/API > CSV > E2K > Excel > computed. Conflicts detected by `ContextBuilder` are retained in its conflict evidence rather than silently overwritten. No new conflict resolution is asserted by this report.\n", encoding="utf-8")
    sources = {"source_priority": ["etabs_api", "etabs_csv", "e2k", "excel", "computed"],
               "models": {k: {"file": v["file"], "section_count": len(v["section_headers"]), "unparsed_count": v["unparsed_count"]} for k,v in parsed.items()}}
    (out / "context_sources.json").write_text(json.dumps(sources, indent=2) + "\n", encoding="utf-8")
    return 0
if __name__ == "__main__": raise SystemExit(main())
