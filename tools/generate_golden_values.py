#!/usr/bin/env python3
"""Regenerate docs/golden_values.md from the sample DOCX and real ETABS exports."""
from __future__ import annotations
import math, re, shutil, sys, tempfile
from pathlib import Path
from zipfile import ZipFile
from xml.etree import ElementTree as ET
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.context_builder import ContextBuilder
SAMPLE = ROOT / "Chatra Bahadur Ramtel.docx"

def docx_text(path: Path) -> str:
    with ZipFile(path) as z:
        root = ET.fromstring(z.read("word/document.xml"))
    return " ".join(n.text or "" for n in root.iter() if n.tag.endswith("}t"))

def get(ctx: dict, key: str):
    value = ctx
    for part in key.split("."):
        value = value.get(part) if isinstance(value, dict) else None
    return value

def main() -> int:
    text = docx_text(SAMPLE)
    samples = {
        "Empirical period amplified (s)": ("0.508", 0.508, "modal.empirical_period_s", 0.001),
        "Rayleigh period X (s)": ("0.602", 0.602, "modal.rayleigh_period_x_s", 0.001),
        "Rayleigh period Y (s)": ("0.531", 0.531, "modal.rayleigh_period_y_s", 0.001),
        "Cd": ("0.1458", 0.1458, "seismic.spectral_coefficient_cd", 0.0001),
        "ESM base shear X (kN)": ("240.02", 240.02, "modal.base_shear_etabs_x", 0.01),
        "ULS displacement X (mm)": ("122.296", 122.296, "drift.uls_max_x_mm", 1e-6),
        "ULS displacement Y (mm)": ("74.744", 74.744, "drift.uls_max_y_mm", 1e-6),
        "SLS displacement X (mm)": ("20.821", 20.821, "drift.sls_max_displacement_x_mm", 0.002 * 20.821),
        "SLS displacement Y (mm)": ("12.428", 12.428, "drift.sls_max_displacement_y_mm", 0.002 * 12.428),
        "Torsion X": ("1.469", 1.469, "irregularity.torsion_x_ratio", 1e-6),
        "Torsion Y": ("1.032", 1.032, "irregularity.torsion_y_ratio", 1e-6),
        "Column maximum steel (%)": ("1.24", 1.24, "design.column.max_provided_pct", 1e-6),
        "Column minimum steel (%)": ("1.026", 1.026, "design.column.min_provided_pct", 1e-6),
        "Beam steel (%)": ("0.764", 0.764, "design.beam.max_provided_pct", 1e-6),
    }
    with tempfile.TemporaryDirectory() as td:
        builder = ContextBuilder()
        ctx = builder.build(ROOT / "tables", ROOT / "sls_tables", ROOT / "tables" / "Chatra Bahadur Ramel_ULS.e2k", ROOT / "inputs" / "Project_Input.xlsx", Path(td))
    lines = ["# Golden Values", "", "Generated by `tools/generate_golden_values.py` from the sample DOCX and real ULS/SLS ETABS exports.", "", "| Metric | Sample value (DOCX) | Computed value | Tolerance | Result | Source |", "|---|---:|---:|---:|---|---|"]
    for metric, (needle, expected, key, tolerance) in samples.items():
        sample_present = needle in text
        actual = get(ctx, key)
        if actual is None or (isinstance(actual, str) and actual.startswith("UNRESOLVED")):
            result = "UNRESOLVED"; actual_text = "UNRESOLVED"
        else:
            actual_float = float(actual); actual_text = f"{actual_float:.6g}"
            result = "PASS" if sample_present and math.isclose(expected, actual_float, abs_tol=tolerance, rel_tol=0.0) else ("UNRESOLVED" if not sample_present else "FAIL")
        source = builder.source_details.get(key, key)
        if isinstance(source, dict):
            source = f"{source.get('file','')}; {source.get('column','')}; {source.get('filter','')}"
        sample_text = f"{expected:g}" if sample_present else f"UNRESOLVED (DOCX lacks {needle})"
        lines.append(f"| {metric} | {sample_text} | {actual_text} | {tolerance:g} | {result} | {source} |")
    lines += ["", "Sample values are validated by searching the untouched sample DOCX; computed values are read from the ContextBuilder output. ULS comparisons are exact at the displayed source precision. SLS comparisons use the owner-approved 0.2% tolerance.", ""]
    (ROOT / "docs" / "golden_values.md").write_text("\n".join(lines), encoding="utf-8")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
